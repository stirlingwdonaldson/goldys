-- Complete recipe observations own their direct lines: a removed line is absent from the next
-- snapshot, while old snapshots and raw evidence remain immutable. V99 is used by the wastage PR.
CREATE TABLE canonical_recipe_definition (
id uuid PRIMARY KEY, logical_entity_id uuid NOT NULL, source_system varchar(255) NOT NULL,
source_record_ref varchar(512) NOT NULL, raw_record_id uuid NOT NULL REFERENCES raw_record(id),
valid_from timestamp(6) with time zone NOT NULL, valid_to timestamp(6) with time zone,
recorded_at timestamp(6) with time zone NOT NULL, superseded_at timestamp(6) with time zone,
recipe_id integer,
name text,
folder_id integer,
active boolean,
locked boolean,
portion_count numeric(28,12),
portion_size numeric(28,12),
unit_id integer,
unit text,
total_cost numeric(28,12),
cost_per_portion numeric(28,12),
cost_per_portion_including_labour numeric(28,12),
labour_cost numeric(28,12),
selling_price_including_gst numeric(28,12),
revenue_excluding_gst numeric(28,12),
gst numeric(28,12),
food_cost_percent numeric(28,12),
gross_profit numeric(28,12),
description text,
menu_description text,
hints text,
preparation_minutes numeric(28,12),
production_item boolean,
countable_on_stocktake boolean,
video_url text,
recipe_date text,
created_by_name text,
difficulty_rating integer,
barcode text,
stock_category_id integer,
food_cost_limit numeric(28,12),
food_cost_limit_including_labour numeric(28,12),
stocks_raw_record_id uuid NOT NULL REFERENCES raw_record(id), usages_raw_record_id uuid NOT NULL REFERENCES raw_record(id)
);
CREATE UNIQUE INDEX uq_canonical_recipe_definition_current ON canonical_recipe_definition(source_system,source_record_ref) WHERE superseded_at IS NULL;
CREATE TABLE canonical_recipe_definition_stocks (snapshot_id uuid NOT NULL REFERENCES canonical_recipe_definition(id),line_order integer NOT NULL,
line_id integer,
stock_id integer,
stock_code text,
description text,
supplier_name text,
supplier_stock_code text,
quantity numeric(28,12),
unit_id integer,
unit text,
stock_pack_size numeric(28,12),
stock_unit_id integer,
stock_unit text,
cost_per_pack numeric(28,12),
cost numeric(28,12),
usable_percent numeric(28,12),
wastage_percent numeric(28,12),
broken_link boolean,
PRIMARY KEY(snapshot_id,line_order));
CREATE TABLE canonical_recipe_definition_usages (snapshot_id uuid NOT NULL REFERENCES canonical_recipe_definition(id),line_order integer NOT NULL,
line_id integer,
recipe_id integer,
name text,
quantity numeric(28,12),
unit_id integer,
unit text,
original_portion_size numeric(28,12),
original_unit_id integer,
original_unit text,
converted_quantity numeric(28,12),
source_cost_per_portion numeric(28,12),
cost numeric(28,12),
cost_including_labour numeric(28,12),
broken_link boolean,
PRIMARY KEY(snapshot_id,line_order));
CREATE TABLE canonical_recipe_catalog (
id uuid PRIMARY KEY, logical_entity_id uuid NOT NULL, source_system varchar(255) NOT NULL,
source_record_ref varchar(512) NOT NULL, raw_record_id uuid NOT NULL REFERENCES raw_record(id),
valid_from timestamp(6) with time zone NOT NULL, valid_to timestamp(6) with time zone,
recorded_at timestamp(6) with time zone NOT NULL, superseded_at timestamp(6) with time zone
);
CREATE UNIQUE INDEX uq_canonical_recipe_catalog_current ON canonical_recipe_catalog(source_system,source_record_ref) WHERE superseded_at IS NULL;
CREATE TABLE canonical_recipe_catalog_folders (snapshot_id uuid NOT NULL REFERENCES canonical_recipe_catalog(id),line_order integer NOT NULL,
folder_id integer,
parent_id integer,
name text,
PRIMARY KEY(snapshot_id,line_order));
CREATE TABLE canonical_recipe_catalog_allocations (snapshot_id uuid NOT NULL REFERENCES canonical_recipe_catalog(id),line_order integer NOT NULL,
entity_type text,
entity_id integer,
outlet_id integer,
deallocated boolean,
PRIMARY KEY(snapshot_id,line_order));
CREATE TABLE canonical_recipe_catalog_evidence(snapshot_id uuid NOT NULL REFERENCES canonical_recipe_catalog(id),raw_record_id uuid NOT NULL REFERENCES raw_record(id));
CREATE TABLE resolved_recipe_definition(recipe_id integer PRIMARY KEY, definition jsonb NOT NULL);
CREATE TABLE resolved_recipe_catalog(id integer PRIMARY KEY, catalog jsonb NOT NULL);
